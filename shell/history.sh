# ═══════════════════════════════════════════════════════════════════════
# history.sh —— 歷史紀錄設定（zsh 專用）
# ═══════════════════════════════════════════════════════════════════════
#
# 為什麼這個檔案值得存在：Ctrl-R 的價值完全取決於歷史「夠不夠長」與
# 「夠不夠乾淨」。歷史是 fzf 的燃料 —— 沒有歷史，Ctrl-R 再快也搜不到東西。
#
# ── 為什麼對 bash 直接早退 ──────────────────────────────────────────
#
# setopt 是 zsh 專屬的內建指令，bash 沒有。而且 bash 的歷史機制本身不同：
# 選項是靠 shopt 與 HISTCONTROL，名稱與語意都對不上。
# 硬移植會得到一個「看起來設了但行為不一樣」的半套 —— 那比沒設更糟。
[ -n "$ZSH_VERSION" ] || return 0


# ── HISTFILE：只在還沒有人設的時候才設 ──────────────────────────────
#
# 為什麼不直接指定：公司機器可能已經把歷史存到別的地方。覆蓋掉的話，
# Ctrl-R 會搜不到你在那台機器上累積的歷史 —— 那是實際的損失，
# 而且是安靜發生的（不會報錯，只是搜不到）。
#
# := 的語意是「未設定或空值時才賦值」。你自己的機器上 omz 已經設成
# 同一個路徑了，所以行為完全不變。
: "${HISTFILE:=$HOME/.zsh_history}"


# ── 長度：只往上調，絕不往下砍 ──────────────────────────────────────
#
# 要修的問題：omz 的預設是 HISTSIZE=50000 但 SAVEHIST=10000 ——
# 記憶體裡留五萬筆，卻只寫一萬筆進檔案。關掉終端機就掉了 4/5。
# 50000 筆的檔案也才幾 MB，沒有理由省。
#
# ⚠️ 但一定要用「只升不降」而不是直接賦值。
#
#    如果公司機器已經設得比 50000 更大，硬蓋下去等於刪你的歷史 ——
#    SAVEHIST 變小，下次寫檔時超出的舊紀錄就被截掉，
#    而且完全沒有提示，等你按 Ctrl-R 找不到東西時已經來不及了。
#
#    這是整個檔案裡唯一可能造成「實際資料損失」的地方，所以要守住。
#    這個寫法就是 omz lib/history.zsh 自己在用的做法（它也不敢直接蓋）。
#
# ${VAR:-0} 是保險：zsh 的 SAVEHIST 預設可能是空值，
# 空值丟給 [ -lt ] 會噴 "integer expression expected"。
if [ "${HISTSIZE:-0}" -lt 50000 ]; then
  HISTSIZE=50000        # 記憶體中保留的筆數
fi
if [ "${SAVEHIST:-0}" -lt 50000 ]; then
  SAVEHIST=50000        # 寫入檔案的筆數
fi


# ── 行為 ────────────────────────────────────────────────────────────
#
# 有 omz 的機器上，其中四項（EXTENDED_HISTORY、SHARE_HISTORY、
# HIST_IGNORE_SPACE、HIST_VERIFY）omz 已經設了，重複設一次無害。
# 真正的增量是 HIST_IGNORE_ALL_DUPS、HIST_REDUCE_BLANKS、HIST_FIND_NO_DUPS。
#
# 沒有 omz 的機器上，這七項全都是新增的。
#
# 這七項是「無條件設定」的 —— 跟上面的長度不同，它們沒有做只升不降的保護。
# 這樣做是安全的，因為 setopt 只改「之後怎麼記錄與搜尋」，
# 不會回頭刪掉任何已經存在的歷史。
#
# 不想要其中某一項（最常見的是 SHARE_HISTORY —— 多個視窗即時共享歷史，
# 有些人很不習慣），在 ~/.zshrc 的 source 那行「之後」加一行就行：
#
#   unsetopt SHARE_HISTORY
#
# 後執行的贏。這也是整個最小安裝模式取消任何一項設定的通則。
setopt EXTENDED_HISTORY       # 記錄時間戳與執行時間
setopt SHARE_HISTORY          # 多個終端機即時共享歷史
setopt HIST_IGNORE_ALL_DUPS   # 重複指令只保留最後一次（讓 Ctrl-R 結果乾淨）
                              # 比 omz 的 HIST_IGNORE_DUPS 強：
                              # 那個只擋「連續」重複，這個擋全部
setopt HIST_IGNORE_SPACE      # 以空白開頭的指令不記錄 —— 打密碼時很有用
setopt HIST_REDUCE_BLANKS     # 存檔前去掉多餘空白
setopt HIST_VERIFY            # 用 !! 或 !$ 展開後先顯示，按 Enter 才執行
setopt HIST_FIND_NO_DUPS      # 搜尋時跳過重複結果
