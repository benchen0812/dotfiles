#
# 這個檔案是「自足」的：不依賴 oh-my-zsh、不依賴任何套件，bash 和 zsh 都能用。
#
# alias 和 function 的分界：需要參數處理、條件判斷、多行邏輯的寫成 function，
# 單純換個名字的寫成 alias。
#
# ⚠️ 這裡刻意只放「新增指令」，不放「改掉既有指令」。
#    這個檔案會被載進公司機器 —— 多一個 mkcd 是安全的，
#    改掉 ls 或 cd 的行為不是。要改行為的東西留在 zsh/custom/。


# 建立目錄後直接進去。`mkdir -p a/b/c && cd a/b/c` 的簡寫。
#
# 兩個 -- 是為了讓開頭是 - 的目錄名也能用 ——
# 沒有它的話 `mkcd -foo` 會把 -foo 當成 mkdir 的參數。
# shellcheck disable=SC2164
# SC2164 建議寫成 `cd ... || exit`。這裡刻意不照做：
# 這是函式不是腳本，cd 失敗時函式回非零就是正確行為 ——
# 而 || exit 會把使用者的整個互動 shell 關掉。
mkcd() {
  mkdir -p -- "$1" && cd -- "$1"
}

# 找出目前目錄底下最大的 N 個檔案（預設 10 個）。
#
# sort -h 是「human-numeric」，看得懂 1K / 2M / 3G。GNU 和 BSD 都支援，
# 但它不是 POSIX 標準，所以還是探測一次比較安全。
#
# 探測寫在函式「內部」而不是檔案頂端 —— 這是刻意的：
# 只有真的呼叫 biggest 才付那個 fork 的成本。寫在頂端的話，
# 每開一次終端機都要多 fork 一次，而 biggest 一個月用不到一次。
biggest() {
  if sort -rh </dev/null >/dev/null 2>&1; then
    du -ah . 2>/dev/null | sort -rh | head -n "${1:-10}"
  else
    # 退回純數字排序。單位變成 KB（du -k 的區塊大小），
    # 少了 M/G 的可讀性，但排序結果是對的。
    du -ak . 2>/dev/null | sort -rn | head -n "${1:-10}"
  fi
}
